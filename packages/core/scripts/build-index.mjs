// Build script: fetch Hafs quran-simple from alquran.cloud, emit quran-data.ts + index stats.
// Fallback: small offline fixture (Al-Fatiha + Al-Ikhlas) so builds/tests never break offline.
// Usage: pnpm --filter @bakemono_san/verset-finder build:data
import { writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outTs = join(root, "src", "quran-data.ts");
const outJson = join(root, "data", "quran-simple.json");

const FALLBACK_SURAHS = [
  {
    number: 1,
    ayahs: [
      { number: 1, numberInSurah: 1, text: "بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ" },
      { number: 2, numberInSurah: 2, text: "الْحَمْدُ لِلَّهِ رَبِّ الْعَالَمِينَ" },
      { number: 3, numberInSurah: 3, text: "الرَّحْمَٰنِ الرَّحِيمِ" },
      { number: 4, numberInSurah: 4, text: "مَالِكِ يَوْمِ الدِّينِ" },
      { number: 5, numberInSurah: 5, text: "إِيَّاكَ نَعْبُدُ وَإِيَّاكَ نَسْتَعِينُ" },
      { number: 6, numberInSurah: 6, text: "اهْدِنَا الصِّرَاطَ الْمُسْتَقِيمَ" },
      { number: 7, numberInSurah: 7, text: "صِرَاطَ الَّذِينَ أَنْعَمْتَ عَلَيْهِمْ غَيْرِ الْمَغْضُوبِ عَلَيْهِمْ وَلَا الضَّالِّينَ" },
    ],
  },
  {
    number: 112,
    ayahs: [
      { number: 6223, numberInSurah: 1, text: "قُلْ هُوَ اللَّهُ أَحَدٌ" },
      { number: 6224, numberInSurah: 2, text: "اللَّهُ الصَّمَدُ" },
      { number: 6225, numberInSurah: 3, text: "لَمْ يَلِدْ وَلَمْ يُولَدْ" },
      { number: 6226, numberInSurah: 4, text: "وَلَمْ يَكُن لَّهُ كُفُوًا أَحَدٌ" },
    ],
  },
];

async function main() {
  let surahs = null;
  let edition = "quran-simple";
  try {
    const res = await fetch("https://api.alquran.cloud/v1/quran/quran-simple");
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const json = await res.json();
    if (json?.data?.surahs?.length === 114) surahs = json.data.surahs;
    else throw new Error("unexpected payload");
    console.log(`[build-index] fetched ${surahs.length} surahs from api.alquran.cloud`);
  } catch (err) {
    console.warn(`[build-index] network fetch failed (${err.message}); using offline fixture (Fatiha + Ikhlas).`);
    surahs = FALLBACK_SURAHS;
    edition = "quran-simple-fixture";
  }
  const count = surahs.reduce((n, s) => n + (s.ayahs?.length ?? 0), 0);
  await mkdir(join(root, "data"), { recursive: true });
  await writeFile(outJson, JSON.stringify({ edition, surahs }, null, 1));
  const ts =
    `// AUTO-GENERATED by scripts/build-index.mjs — do not edit.\n` +
    `// Edition: ${edition} (${count} ayahs). Source: api.alquran.cloud (Tanzil/KFUPM data).\n` +
    `// Quran text is NOT under MIT — see package README for attribution.\n` +
    `export default ${JSON.stringify({ surahs })} as const;\n`;
  await writeFile(outTs, ts);
  console.log(`[build-index] wrote ${outTs} + ${outJson} (${count} ayahs, edition=${edition})`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
